// Generate the native server entrypoints committed to the connected source tree.
// Keep originals outside api/: Vercel must discover exactly twelve handlers.
import { build } from 'vite';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import assert from 'node:assert/strict';

const root = resolve(import.meta.dirname, '..');
const entries = [
  ['server/passport.ts', 'api/passport.js'],
  ['server/workspace.ts', 'api/workspace.js'],
  ['scripts/test-connectors-entry.mjs', 'api/connectors/[action].js'],
];
for (const [entry, output] of entries) {
  const result = await build({ root, configFile: false, logLevel: 'error',
    build: { ssr: resolve(root, entry), target: 'node24', write: false, minify: false,
      rollupOptions: { output: { format: 'es', inlineDynamicImports: true } } } });
  assert.equal(result.output.length, 1, 'Expected one native runtime for ' + entry);
  const code = '// Generated by scripts/build-server-runtimes.mjs from ' + entry + '. Do not edit this artifact.\n' + result.output[0].code;
  const path = resolve(root, output);
  if (process.argv.includes('--check')) {
    assert.equal((await readFile(path, 'utf8')).replaceAll('\r\n', '\n'), code,
      'Stale server runtime: ' + output + '. Run npm run build:server and commit the generated files.');
  } else {
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, code);
  }
}
console.log('PASS native server runtimes ' + (process.argv.includes('--check') ? 'match their source' : 'generated'));
