import assert from 'node:assert/strict';
import { existsSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
const path = new URL('../api/_lib/tradovate-performance.js', import.meta.url);
assert(existsSync(path), 'Performance parser must exist before history can enter the ledger');
const { parsePerformanceReport } = await import(pathToFileURL(path.pathname.replace(/^\/(?:([A-Z]:))/, '$1')).href);
const header = 'symbol,_priceFormat,_priceFormatType,_tickSize,buyFillId,sellFillId,qty,buyPrice,sellPrice,pnl,boughtTimestamp,soldTimestamp,duration';
const row = 'MNQZ6,-2,0,0.25,90000000000000001,90000000000000002,2,20000,20003,$12.00,11/02/2026 00:00:00,11/02/2026 00:00:10,10sec';
const window = { startDate: '2026-11-01', endDate: '2026-11-03', timeZone: 'UTC', timezoneOffset: 0 };
export const fixtureCsv = `${header}\r\n${row}\r\n`;
const result = parsePerformanceReport(fixtureCsv, '71', window);
assert.equal(result.trades.length, 1);
assert.equal(result.trades[0].id, 'tradovate-71:90000000000000001:90000000000000002');
assert.equal(result.trades[0].date, '2026-11-02T00:00:10.000Z');
assert.equal(result.trades[0].pnl, 12);
assert.equal(result.trades[0].side, 'Long');
assert.equal(result.trades[0].risk, 0);
assert.equal(result.trades[0].source.accountId, '71');
console.log('Performance parser: strict synthetic long slice passed');
const short = row.replace('$12.00', '$(12.00)').replace('20000,20003', '20003,20000').replace('00:00:00,11/02/2026 00:00:10', '00:00:10,11/02/2026 00:00:00');
const negative = parsePerformanceReport(`\uFEFF${header}\r\n${short.split(',').map(value => `"${value}"`).join(',')}\r\n`, '71', window);
assert.equal(negative.trades[0].pnl, -12);
assert.equal(negative.trades[0].side, 'Short');
assert.equal(negative.trades[0].entry, 20000);
assert.equal(negative.trades[0].exit, 20003);
assert.equal(negative.trades[0].id, result.trades[0].id, 'Correction cannot change identity');
assert.notEqual(parsePerformanceReport(fixtureCsv, '72', window).trades[0].id, result.trades[0].id);
assert.equal(parsePerformanceReport(`${header}\r\n`, '71', window).trades.length, 0);
const malformed = [fixtureCsv + row + '\r\n', fixtureCsv.replace(',2,20000', ',1.5,20000'), fixtureCsv.replace('$12.00', '$13.00'), fixtureCsv.replace('11/02/2026', '02/30/2026'), fixtureCsv.replace('MNQZ6', 'UNKNOWNZ6'), fixtureCsv.replace(',10sec', ',9hour'), fixtureCsv.replace('90000000000000001', '9e16'), fixtureCsv.replace('00:00:10', '00:00:00'), fixtureCsv.replace('0.25', '0'), fixtureCsv.slice(0, -2), fixtureCsv.replace('duration', 'pnl'), fixtureCsv.replace(',20000,', ',NaN,'), fixtureCsv.replace('00:00:10', '24:00:00'), 'x'.repeat(524289)];
for (const text of malformed) assert.throws(() => parsePerformanceReport(text, '71', window), /invalid_performance_report/);
for (const range of [{ ...window, timeZone: 'America/New_York' }, { ...window, startDate: 'no-date' }, { ...window, startDate: '2026-11-03' }, { ...window, endDate: '2026-02-30' }]) assert.throws(() => parsePerformanceReport(fixtureCsv, '71', range), /invalid_performance_report/);
console.log('Performance parser: accounting/quoted/short/UTC/identity and fail-closed cases passed');
